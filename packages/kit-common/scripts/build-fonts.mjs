// Writes Common's typefaces, the ones its font-* tokens name, so AUGUR serves them itself and a
// deployment with no internet still shows them. Fontsource (ADR 0015 in the AUGUR repository) ships
// each face as a stylesheet and its files; this copies the stylesheets below into one, and the files
// they name next to it:
//   dist/fonts.css     every @font-face, its url()s pointing at fonts/
//   dist/fonts/        the font files those name, and nothing else
// The kit bundle serves both, and links fonts.css with the kit's other stylesheets.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

/** The faces and weights the kit uses: Jost for text and titles (font-sans), Nunito where it is rounded (font-rounded). */
export const FACES = [
  '@fontsource/jost/200.css',
  '@fontsource/jost/300.css',
  '@fontsource/jost/400.css',
  '@fontsource/jost/500.css',
  '@fontsource/jost/600.css',
  '@fontsource/nunito/400.css',
  '@fontsource/nunito/600.css',
];

const out = join(root, 'dist/fonts');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

let copied = 0;
const css = FACES.map((face) => {
  const file = require.resolve(face);
  const text = readFileSync(file, 'utf8').replace(/url\((['"]?)([^'")]+)\1\)/g, (_, _q, url) => {
    const name = basename(url);
    copyFileSync(join(dirname(file), url), join(out, name));
    copied += 1;
    return `url(./fonts/${name})`;
  });
  return `/* ${face} */\n${text.trim()}\n`;
});

writeFileSync(join(root, 'dist/fonts.css'), `/* Generated by scripts/build-fonts.mjs from Fontsource. Do not edit. */\n${css.join('\n')}`);
console.log(`kit-common: wrote ${FACES.length} faces, ${copied} font files`);
