// Builds AUGUR's tokens with Style Dictionary from the three token files in
// tokens/ (W3C design tokens format): common.tokens.json (both kits),
// shell.tokens.json (Aerie, the shell kit) and app.tokens.json (Quill, the
// app kit). Those files are the only place tokens are edited (ADR 0015). From
// them it writes:
//   dist/tokens.css         every token as a CSS custom property, on :root, then each motion
//                           token's reduced value ($extensions.augur.reduced) under reduced motion
//   dist/theme.css          the Tailwind v4 theme for Common: Tailwind's own palette and scales removed
//   dist/theme-shell.css    what Aerie adds to it (the shell set)
//   dist/theme-app.css      what Quill adds to it (the app set)
//   src/generated/tokens.ts the typed token map
import StyleDictionary from 'style-dictionary';
import { appendFileSync, mkdirSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = 'Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit.';

// A token's CSS name is its own name, whatever group it sits in: `color.slate` is `--slate`.
const name = (token) => token.path.at(-1);

// The typed map keeps a reference as `{name}`, as the kits' code expects.
const raw = (token) => String(token.original.$value).replace(/\{(?:[a-z0-9-]+\.)*([a-z0-9-]+)\}/g, '{$1}');

/** Which set a token belongs to: common, shell or app, from the file it is written in. */
const setOf = (token) => basename(token.filePath).replace(/\.tokens\.json$/, '');

/**
 * Where a token goes in Tailwind's theme, as `[theme variable, ...extra]`, or
 * nothing when Tailwind has no utility for it (durations, layers, effects):
 * those stay CSS variables the kits read. Each theme variable points at the
 * token's own CSS variable, so a kit that sets a token's value for its ground
 * changes the utility too.
 */
const themed = (token, all) => {
  const n = token.name;
  const v = `var(--${n})`;
  const group = token.path[0];
  if (group === 'color') return [[`--color-${n}`, v]];
  if (group === 'space') return [[`--spacing-${n.replace(/^space-/, '')}`, v]];
  if (group === 'radius') return [[`--radius-${n.replace(/^radius-/, '')}`, v]];
  if (group === 'shadow') return [[`--shadow-${n.replace(/^shadow-/, '')}`, v]];
  if (group === 'font') return [[`--font-${n.replace(/^font-/, '')}`, v]];
  if (group === 'tracking') return [[`--tracking-${n.replace(/^tracking-/, '')}`, v]];
  if (group === 'motion' && n.startsWith('ease-')) return [[`--ease-${n.replace(/^ease-/, '')}`, v]];
  if (group === 'structure' && n.startsWith('measure-')) return [[`--container-${n.replace(/^measure-/, '')}`, v]];
  if (group === 'structure' && (n.startsWith('edge') || n.startsWith('target-'))) return [[`--spacing-${n}`, v]];
  if (group === 'type' && n.startsWith('weight-')) return [[`--font-weight-${n.replace(/^weight-/, '')}`, v]];
  if (group === 'type' && n.startsWith('type-')) {
    // A type role is one utility: its size, with its own leading, tracking and weight when it has them.
    const role = n.replace(/^type-/, '');
    const out = [[`--text-${role}`, v]];
    for (const [part, prefix] of [['line-height', 'leading'], ['letter-spacing', 'tracking'], ['font-weight', 'weight']]) {
      if (all.has(`${prefix}-${role}`)) out.push([`--text-${role}--${part}`, `var(--${prefix}-${role})`]);
    }
    return out;
  }
  return [];
};

const theme = (set, reset) => ({ dictionary }) => {
  const all = new Set(dictionary.allTokens.map((t) => t.name));
  const lines = dictionary.allTokens.filter((t) => setOf(t) === set).flatMap((t) => themed(t, all)).map(([k, v]) => `  ${k}: ${v};`);
  // Tailwind's own palette and scales are cleared first, so only AUGUR's tokens exist as classes.
  // `inline reference`: a utility uses the token's variable itself, and Tailwind writes no variables
  // of its own (tokens.css already has them; Tailwind's `--font-sans: var(--font-sans)` would be a loop).
  const clear = reset ? '  --*: initial;\n' : '';
  return `/* ${header} */\n@theme inline reference {\n${clear}${lines.join('\n')}\n}\n`;
};

const sd = new StyleDictionary({
  source: [join(root, 'tokens/*.tokens.json')],
  usesDtcg: true,
  log: { verbosity: 'silent' },
  hooks: {
    transforms: { 'name/own': { type: 'name', transform: name } },
    fileHeaders: { augur: () => [header] },
    formats: {
      'typescript/token-map': ({ dictionary }) => {
        const map = Object.fromEntries(dictionary.allTokens.map((t) => [t.name, raw(t)]));
        return `// ${header}\nexport const tokens = ${JSON.stringify(map, null, 2)} as const;\n\nexport type TokenName = keyof typeof tokens;\n\n/** A CSS var() reference to a token, for use in component styles. */\nexport const token = (name: TokenName): string => \`var(--\${name})\`;\n`;
      },
      'tailwind/common': theme('common', true),
      'tailwind/shell': theme('shell', false),
      'tailwind/app': theme('app', false),
    },
  },
  platforms: {
    css: {
      transforms: ['name/own'],
      buildPath: `${join(root, 'dist')}/`,
      files: [
        { destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true, fileHeader: 'augur' } },
        { destination: 'theme.css', format: 'tailwind/common' },
        { destination: 'theme-shell.css', format: 'tailwind/shell' },
        { destination: 'theme-app.css', format: 'tailwind/app' },
      ],
    },
    ts: {
      transforms: ['name/own'],
      buildPath: `${join(root, 'src/generated')}/`,
      files: [{ destination: 'tokens.ts', format: 'typescript/token-map' }],
    },
  },
});

mkdirSync(join(root, 'dist'), { recursive: true });
await sd.buildAllPlatforms();
const { allTokens } = await sd.getPlatformTokens('css');

// Reduced motion, from the system or the page's own setting (data-motion="reduce" on <html>, which a
// host sets from a person's preference): one switch for both. Each token with a reduced value takes it,
// so moves become near-instant, nothing travels and loops stop. Custom properties inherit, so the
// switch reaches every part, in shadow roots too.
const reduced = allTokens.filter((t) => t.$extensions?.augur?.reduced !== undefined);
const lines = (indent) => reduced.map((t) => `${indent}--${t.name}: ${t.$extensions.augur.reduced};`).join('\n');
appendFileSync(
  join(root, 'dist/tokens.css'),
  `\n:root[data-motion='reduce'] {\n${lines('  ')}\n}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${lines('    ')}\n  }\n}\n`,
);
console.log(`kit-common: wrote ${allTokens.length} tokens, ${reduced.length} with a reduced-motion value`);
